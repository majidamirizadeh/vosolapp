/** نام منطقه‌ها به ترتیب نمایش */
export const REGION_NAMES = Object.keys(REGIONS);

/** منطقهٔ یک امور (نام امور مثل OMOORS) یا "" */
export function regionOf(omoor) {
  const norm = (s) => String(s || "").replace(/\u200c/g, " ").trim();
  for (const [name, list] of Object.entries(REGIONS)) if (list.some((o) => norm(o) === norm(omoor))) return name;
  return "";
}
